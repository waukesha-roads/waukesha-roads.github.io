// Builds the app's data files from the raw OSM download and the street list.
//
//   node tools/build-data.mjs
//
// Inputs
//   raw/boundary.json, raw/roads.json   (from tools/fetch-osm.mjs)
//   data/streets.csv                    (THE CURATED STREET LIST - edit this in Excel)
//
// Outputs (loaded by index.html)
//   data/boundary.js     city limits polygon
//   data/streets.js      street index + road geometry
//
// If data/streets.csv does not exist, a placeholder one is created from every
// named road in OSM so the game has something to run on.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const r5 = (n) => Math.round(n * 1e5) / 1e5;

// ---------------------------------------------------------------- boundary
function assembleRings(members, role) {
  const pieces = members
    .filter((m) => m.type === "way" && m.role === role && m.geometry)
    .map((m) => m.geometry.map((p) => [r5(p.lat), r5(p.lon)]));
  const same = (a, b) => a[0] === b[0] && a[1] === b[1];
  const rings = [];
  while (pieces.length) {
    let ring = pieces.shift();
    let grew = true;
    while (!same(ring[0], ring[ring.length - 1]) && grew) {
      grew = false;
      for (let i = 0; i < pieces.length; i++) {
        const p = pieces[i];
        const end = ring[ring.length - 1];
        if (same(end, p[0])) ring = ring.concat(p.slice(1));
        else if (same(end, p[p.length - 1])) ring = ring.concat(p.slice(0, -1).reverse());
        else continue;
        pieces.splice(i, 1);
        grew = true;
        break;
      }
    }
    rings.push(ring);
  }
  return rings;
}

