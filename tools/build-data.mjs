// ---------------------------------------------------------------- build index
// blocks column examples:  "100-1900"   or   "100-900 N; 100-1500 S"
function parseBlocks(s) {
  if (!s) return [];
  return s.split(";").map((part) => {
    const m = part.trim().match(/^(\d+)\s*-\s*(\d+)\s*(.*)$/);
    return m ? { from: +m[1], to: +m[2], label: m[3].trim() } : { from: null, to: null, label: part.trim() };
  });
}

// "Dead end" = courts, circles and streets with only one way in (worked out below for Tertiary streets)
const VALID_CAT = ["Primary", "Secondary", "Tertiary", "Dead end"];
const STATION_NAMES = Object.values(STATIONS).map((s) => s.name);
const streets = [];
const missing = [];
for (const row of parseCSV(readFileSync(CSV_PATH, "utf8"))) {
  if (!row.name) continue;
  const targets = (row.map_name || row.name).split("|").map((s) => s.trim()).filter(Boolean);
  const lines = [];
  const keys = [];
  for (const t of targets) {
    const key = geo.has(t) ? t : geoByNorm.get(norm(t));
    if (key) { lines.push(...geo.get(key).lines); keys.push(norm(key)); }
  }
  if (!lines.length) { missing.push(row.name); continue; }
  const category = VALID_CAT.find((c) => c.toLowerCase() === (row.category || "").toLowerCase()) || "Tertiary";
  streets.push({
    name: row.name,
    category,
    district: row.district ? row.district.split("|").map((s) => s.trim()) : null, // null = work out from map
    // stations whose curated secondary list has this street (Secondary streets only)
    secondaryFor: category === "Secondary" && row.secondary_for
      ? row.secondary_for.split("|").map((s) => s.trim()).filter((s) => {
          if (!STATION_NAMES.includes(s)) console.log(`WARNING: ${row.name}: unknown station "${s}" in secondary_for`);
          return STATION_NAMES.includes(s);
        })
      : [],
    blocks: parseBlocks(row.blocks),
    notes: row.notes || "",
    lines,
    keys, // normalized map names - used to attach addresses, removed before saving
  });
}

// ---------------------------------------------------------------- missing direction prefixes
// Both data sources sometimes drop the direction: e.g. the map has a "Sunset Drive" piece that is
// really the east end of East Sunset Drive. A prefix-less piece that physically connects to its
// North/South/East/West twin is merged into that twin; unconnected ones are left alone.
const DIR_WORDS = ["north", "south", "east", "west"];
const isBare = (k) => !DIR_WORDS.includes(k.split(" ")[0]) && !/^(northwest|northeast|southwest|southeast) /.test(k);
const metersBetween = (a, b) => Math.hypot((a[0] - b[0]) * 111320, (a[1] - b[1]) * 111320 * Math.cos((a[0] * Math.PI) / 180));
function distToLines(p, lines) {
  let best = Infinity;
  for (const l of lines) {
    for (let i = 0; i < l.length - 1; i++) {
      const a = l[i], b = l[i + 1];
      const kx = 111320 * Math.cos((p[0] * Math.PI) / 180), ky = 111320;
      const ax = (a[1] - p[1]) * kx, ay = (a[0] - p[0]) * ky, bx = (b[1] - p[1]) * kx, by = (b[0] - p[0]) * ky;
      const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
      const t = len2 ? Math.max(0, Math.min(1, -(ax * dx + ay * dy) / len2)) : 0;
      best = Math.min(best, Math.hypot(ax + t * dx, ay + t * dy));
    }
  }
  return best;
}
const twinsOf = (bareKey) => streets.filter((st) => st.keys.some((k) => DIR_WORDS.some((d) => k === `${d} ${bareKey}`)));
const merged = [];
for (const st of [...streets]) {
  if (st.keys.length !== 1 || !isBare(st.keys[0])) continue;
  const twins = twinsOf(st.keys[0]);
  if (!twins.length) continue;
  let keep = st.lines;
  let grew = true;
  while (grew) { // repeat so a chain of pieces follows the first one that touches the twin
    grew = false;
    const rest = [];
    for (const piece of keep) {
      // join the twin whose road touches this piece's ends (within 30 m)
      const ends = [piece[0], piece[piece.length - 1]];
      const twin = twins.find((t) => ends.some((e) => distToLines(e, t.lines) <= 30));
      if (twin) { twin.lines.push(piece); merged.push(`${st.name} -> ${twin.name}`); grew = true; } else rest.push(piece);
    }
    keep = rest;
  }
  st.lines = keep;
  if (!keep.length) streets.splice(streets.indexOf(st), 1);
}
if (merged.length) console.log("merged prefix-less map pieces: " + [...new Set(merged)].join(", "));

// ---------------------------------------------------------------- courts & dead ends
// A Tertiary street becomes "Dead end" when it is a Court/Circle, or when every connected piece of
// it has only one way in: all the places other roads touch it are within DEAD_END_GAP of each other
// (a cul-de-sac, a lollipop loop, or a stub off a single intersection).
{
  const DEAD_END_GAP = 60; // m - a divided entrance still counts as one way in
  const key = (p) => p[0] + "," + p[1];
  const nodeUse = new Map(); // node -> Set of way names touching it ("" for unnamed)
  for (const w of netSrc.elements) {
    if (!w.geometry) continue;
    const n = w.tags.name ? norm(w.tags.name) : "#" + w.id;
    for (const p of w.geometry) {
      const k = key([r5(p.lat), r5(p.lon)]);
      (nodeUse.get(k) ?? nodeUse.set(k, new Set()).get(k)).add(n);
    }
  }
  const isCourt = (st) => /\b(court|circle)$/.test(norm(st.name));
  let courts = 0, deadEnds = 0;
  for (const st of streets) {
    if (st.category !== "Tertiary") continue;
    if (isCourt(st)) { st.category = "Dead end"; courts++; continue; }
    // own names, plus the prefix-less twin pieces merged into it ("sunset drive" in East Sunset Drive)
    const own = new Set(st.keys.flatMap((k) => [k, k.replace(/^(north|south|east|west|northwest|northeast|southwest|southeast) /, "")]));
    // group the street's lines into connected pieces (shared nodes)
    const pieces = [];
    for (const l of st.lines) {
      const ks = new Set(l.map(key));
      const hits = pieces.filter((pc) => [...ks].some((k) => pc.nodes.has(k)));
      let len = 0;
      for (let i = 1; i < l.length; i++) len += metersBetween(l[i - 1], l[i]);
      const pc = { nodes: ks, pts: [...l], len };
      for (const h of hits) {
        h.nodes.forEach((k) => pc.nodes.add(k));
        pc.pts.push(...h.pts);
        pc.len += h.len;
        pieces.splice(pieces.indexOf(h), 1);
      }
      pieces.push(pc);
    }
    // every piece's junctions sit together (and not at both ends of a short through-street)
    const oneWayIn = pieces.every((pc) => {
      const junctions = pc.pts.filter((p) => [...(nodeUse.get(key(p)) || [])].some((n) => !own.has(n)));
      let span = 0;
      for (const a of junctions) for (const b of junctions) span = Math.max(span, metersBetween(a, b));
      return span <= Math.min(DEAD_END_GAP, pc.len / 2);
    });
    if (oneWayIn) { st.category = "Dead end"; deadEnds++; }
  }
  console.log(`dead ends: ${courts} courts/circles + ${deadEnds} other one-way-in streets`);
}

// ---------------------------------------------------------------- buildings (county Structures)
// Footprints inside the city, packed as integer offsets (1e-5 deg, about 1 m) to keep the file small:
// each building is a list of rings; each ring is [lat0, lon0, dLat1, dLon1, ...] relative to BASE.
const BASE = [42.9, -88.4];
const buildings = []; // { rings: [[lat, lon]...][], bbox }
const pointInRing = (p, ring) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i], [yj, xj] = ring[j];
    if ((yi > p[0]) !== (yj > p[0]) && p[1] < ((xj - xi) * (p[0] - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const inCityLimits = (p) => boundary.outer.some((r) => pointInRing(p, r)) && !boundary.inner.some((r) => pointInRing(p, r));
if (existsSync("raw/buildings.json")) {
  for (const b of read("raw/buildings.json")) {
    const rings = b.rings.map((r) => {
      const pts = [];
      for (const [x, y] of r) {
        const p = [r5(y), r5(x)];
        const last = pts[pts.length - 1];
        if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
      }
      if (pts.length > 1 && pts[0][0] === pts[pts.length - 1][0] && pts[0][1] === pts[pts.length - 1][1]) pts.pop();
      return pts;
    }).filter((r) => r.length >= 3);
    if (!rings.length) continue;
    const o = rings[0];
    const c = [o.reduce((s, p) => s + p[0], 0) / o.length, o.reduce((s, p) => s + p[1], 0) / o.length];
    if (!inCityLimits(c)) continue;
    const lats = o.map((p) => p[0]), lons = o.map((p) => p[1]);
    buildings.push({ rings, bbox: [Math.min(...lats), Math.min(...lons), Math.max(...lats), Math.max(...lons)] });
  }
  const enc = (ring) => {
    const out = [];
    let pl = 0, pn = 0;
    ring.forEach((p, i) => {
      const la = Math.round((p[0] - BASE[0]) * 1e5), lo = Math.round((p[1] - BASE[1]) * 1e5);
      out.push(i ? la - pl : la, i ? lo - pn : lo);
      pl = la; pn = lo;
    });
    return out;
  };
  writeFileSync(
    "data/buildings.js",
    "// Building footprints (Waukesha County 'Structures'), City of Waukesha. Generated by tools/build-data.mjs\n" +
      "// Each building: list of rings; ring = [lat0, lon0, dLat, dLon, ...] in 1e-5 degrees from BUILDING_BASE.\n" +
      `window.BUILDING_BASE = ${JSON.stringify(BASE)};\n` +
      "window.BUILDINGS = " + JSON.stringify(buildings.map((b) => b.rings.map(enc))) + ";\n"
  );
  console.log(`buildings: ${buildings.length} inside the city`);
}
// Grid lookup: which building is an address in (or right next to)?
const bGrid = new Map();
const cellOf = (lat, lon) => `${Math.floor(lat / 0.002)},${Math.floor(lon / 0.002)}`;
buildings.forEach((b, i) => {
  for (let la = Math.floor(b.bbox[0] / 0.002); la <= Math.floor(b.bbox[2] / 0.002); la++)
    for (let lo = Math.floor(b.bbox[1] / 0.002); lo <= Math.floor(b.bbox[3] / 0.002); lo++) {
      const k = `${la},${lo}`;
      if (!bGrid.has(k)) bGrid.set(k, []);
      bGrid.get(k).push(i);
    }
});
function buildingFor(p) {
  const [la, lo] = cellOf(p[0], p[1]).split(",").map(Number);
  let best = -1, bestD = 15; // inside, or within 15 m of the wall
  for (let a = la - 1; a <= la + 1; a++) for (let b = lo - 1; b <= lo + 1; b++) {
    for (const i of bGrid.get(`${a},${b}`) || []) {
      const rings = buildings[i].rings;
      if (pointInRing(p, rings[0])) return i;
      const d = distToLines(p, [[...rings[0], rings[0][0]]]);
      if (d < bestD) { bestD = d; best = i; }
    }
  }
  return best;
}

